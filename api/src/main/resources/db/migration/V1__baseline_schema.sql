create table guest (
    id                   bigint       generated by default as identity primary key,
    wedding_id           bigint       not null references wedding (id),
    -- 100 rather than 255: this holds a person's name, and the reason for the
    -- headroom is foreign names and 4-syllable Korean names, not a URL.
    -- It must never be tightened below what the entity mapping declares —
    -- validate will not tell you.
    name                 varchar(100) not null,
    side                 wedding_side not null,
    -- One of seven: FAMILY / RELATIVE / COUSIN / PARENTS_GUEST / FRIEND /
    -- COWORKER / OTHER. The list changed twice in one day; assume it changes
    -- again, which is why this is varchar and not an enum. Aggregation splits
    -- on this column only.
    group_category       varchar(30)  not null,
    -- The couple's free label ("대학교 동아리 친구들"), and where an unmapped
    -- 관계 from an import file is preserved verbatim. Never aggregated on:
    -- free labels fracture on typing variants.
    group_label          varchar(100),
    -- As entered. An import file usually carries the whole number; the vendor
    -- email carries only the last four digits. Normalising for matching is the
    -- matcher's job, in memory, not a stored derived column.
    contact              varchar(30),
    -- 배려사항 — free text, belongs to the person, carries forward to seating.
    accessibility_note   varchar(500),
    -- Expected is what the couple typed; confirmed is what was verified.
    -- Confirmed is nullable because blank is UNKNOWN, never zero — the
    -- aggregation falls back to expected and counts the guest as 확인 필요.
    expected_attending   boolean      not null,
    confirmed_attending  boolean,
    -- 참석 인원: the guest plus whoever they bring, not the companion count.
    -- The vendor channel's 추가 동행 인원 is converted on the way in.
    expected_party_size  integer      not null,
    confirmed_party_size integer,
    created_by           bigint       not null references app_user (id),
    created_at           timestamptz  not null,
    updated_by           bigint       not null references app_user (id),
    updated_at           timestamptz  not null,
    deleted_at           timestamptz,
    -- A party of zero people is not a party; 불참 is spelled
    -- confirmed_attending = false, not party size 0 — and with `lifecycle` gone
    -- (see the header) there is no second column that could also mean it.
    -- Strictly positive on both slots, and NULL passes a CHECK, so the confirmed
    -- slot keeps meaning "not verified yet".
    --
    -- What this does NOT pin down, since nothing else will say so: the schema
    -- still admits confirmed_attending = false alongside a non-null
    -- confirmed_party_size. Which one the aggregation reads first is #17's, and
    -- the answer has to be attendance — a party size on a 불참 guest is stale
    -- data, not a claim.
    constraint ck_guest_expected_party_size check (expected_party_size > 0),
    constraint ck_guest_confirmed_party_size check (confirmed_party_size > 0),
    -- Implied by the primary key; exists solely as the target of
    -- guest_meal_count's composite FK. Same non-partial reasoning as
    -- ux_meal_type_id_wedding.
    constraint ux_guest_id_wedding unique (id, wedding_id)
);

-- Every ledger read is "this wedding, not deleted". Partial so the index does
-- not carry rows no screen will ever show.
--
-- Note what that costs, because it is invisible otherwise: the import matcher
-- is the one query that must SEE deleted rows, so its predicate does not match
-- this index and it will sequential-scan the wedding's guests. That is
-- acceptable at v1 volumes (200–800 rows per wedding, loaded once per import
-- and matched in memory) and it is not covered by anything else — the matcher
-- has no index of its own. If it ever needs one, the shape is an unfiltered
-- index on wedding_id, not a change to this one.
create index ix_guest_wedding
    on guest (wedding_id)
    where deleted_at is null;

create table guest_meal_count (
    id              bigint  generated by default as identity primary key,
    -- WEDDING_ID HERE IS AN INTEGRITY DEVICE, NOT A ROOT MARKER. Read this
    -- before citing it as precedent.
    --
    -- The standing rule is unchanged: every wedding-scoped aggregate ROOT
    -- carries wedding_id, and anything reached only through its root does not.
    -- guest_meal_count is still not a root, and this column does not make it
    -- one. It is here for one reason: to make a MIXED-wedding row
    -- UNREPRESENTABLE — one whose guest and whose meal type belong to different
    -- weddings. Read that word narrowly; the paragraph on the FKs below says
    -- what it does not cover, and the gap is the interesting part.
    --
    -- SO IT IS AN FK COMPONENT AND NEVER A QUERY PREDICATE. Every read of this
    -- table joins `guest` and filters `guest.deleted_at is null`; nothing
    -- filters this table on its own wedding_id. The column is exactly what
    -- makes the wrong query writable, and the wrong query is the natural one:
    --     select sum(expected_count) from guest_meal_count where wedding_id = ?
    -- silently counts the meals of soft-deleted 하객, because @SQLRestriction
    -- does not reach a native query
    -- (notes/2026-08-10-decision-soft-delete.md, consequence 1). It does not
    -- throw, it over-counts, and over-counting 보증인원 is money. The correct
    -- shape joins:
    --     select sum(gmc.expected_count) from guest_meal_count gmc
    --       join guest g on g.id = gmc.guest_id
    --      where g.wedding_id = ? and g.deleted_at is null
    -- That soft-delete record predates this column, so its warning was written
    -- about tables that did not yet include the one place it bites hardest.
    -- GuestMealCountSchemaTest holds the regression.
    --
    -- No `references wedding (id)`, and that omission is deliberate rather than
    -- missed — it is the only wedding_id in this file without one. Both
    -- composite FKs below already point at a parent whose own wedding_id
    -- references wedding, so the value here cannot be a wedding that does not
    -- exist. A third constraint would enforce nothing and cost an index probe
    -- per write. Do not "fix" it while typing.
    --
    -- The hole it closes: meal_type_id arrives in the request body (#14), so it
    -- never passes through CurrentWedding resolution. With single-column FKs, a
    -- row joining wedding 1's guest to wedding 2's meal type inserts cleanly —
    -- and the API then answers differently for a nonexistent id (FK violation)
    -- than for another wedding's id (success), which is precisely the
    -- wedding-id oracle that
    -- notes/2026-08-10-decision-cross-tenant-status-code.md exists to deny.
    -- Service-layer validation would also close THAT, but only where someone
    -- remembers to write it; the composite FKs below close it for every writer
    -- that will ever exist.
    --
    -- #80 (the wedding_id allowlist meta-test) MUST carry this table as an
    -- explicit exception: it has the column and is not a root.
    --
    -- No deleted_at: it is not a row a user deletes, it is a count they set to
    -- zero.
    wedding_id      bigint  not null,
    guest_id        bigint  not null,
    meal_type_id    bigint  not null,
    expected_count  integer not null,
    confirmed_count integer,
    -- Composite, and that is the whole mechanism: both parents must agree with
    -- this row's wedding_id, so guest and meal type are forced into the same
    -- wedding by the database. They replace the single-column FKs rather than
    -- supplementing them — each subsumes the one it replaces.
    --
    -- WHAT THEY DO NOT CLOSE, because "unrepresentable" reads as more than it
    -- says. They force the row to be INTERNALLY consistent, not to be OWNED by
    -- the caller's wedding. A row wholly inside another wedding inserts cleanly:
    --     insert into guest_meal_count (wedding_id, guest_id, meal_type_id, expected_count)
    --     values (2, 200, 20, 2);   -- issued by a wedding-1 caller
    -- All three columns agree and the FKs have nothing to object to. The
    -- plausible #14 implementation — load the guest, take its wedding_id — writes
    -- exactly that row into a stranger's ledger. Worse, the outcomes then differ:
    -- a second identical attempt returns ux_guest_meal_count_guest_type where the
    -- first returned success, which is a cross-wedding EXISTENCE ORACLE on the
    -- victim's guests — the same thing
    -- notes/2026-08-10-decision-cross-tenant-status-code.md denies. Only the
    -- resolver closes it; that is #5/#14's and no constraint on this table will
    -- ever do it.
    --
    -- And they do not imply a LIVE parent. Both targets are non-partial unique
    -- constraints, necessarily — Postgres will not point an FK at a partial
    -- index — so a soft-deleted guest and a soft-deleted meal_type each still
    -- accept new rows here. Same wedding only, so it is not an isolation
    -- problem; but "a type in use cannot be deleted" (2026-08-06) and the
    -- soft-delete filter have no database backstop on this table, and
    -- @SQLRestriction does not reach it. #10/#14 own that test.
    constraint fk_guest_meal_count_guest
        foreign key (guest_id, wedding_id) references guest (id, wedding_id),
    constraint fk_guest_meal_count_meal_type
        foreign key (meal_type_id, wedding_id) references meal_type (id, wedding_id),
    constraint ux_guest_meal_count_guest_type unique (guest_id, meal_type_id),
    -- >= 0 here, unlike party size: zero is a meaningful count. "3명 중 2명만
    -- 식사" makes the other type's row a real, deliberate zero.
    constraint ck_guest_meal_count_expected check (expected_count >= 0),
    constraint ck_guest_meal_count_confirmed check (confirmed_count >= 0)
);

-- Supports the lookup behind "a type in use cannot be deleted" (2026-08-06).
-- UNDECIDED, and the index does not settle it: whether "in use" means a row
-- exists for this type, or a row with a non-zero count exists. Those differ for
-- a guest whose count was set to 0, and #10 owns the answer. If it turns out to
-- be the non-zero reading, this index still serves it — just less selectively.
create index ix_guest_meal_count_meal_type on guest_meal_count (meal_type_id);


-- ---------------------------------------------------------------------------
-- The audit log. Append-only: no deleted_at, because a deletable audit log is
-- not an audit log. This is what makes "이 숫자 누가 바꿨어?" answerable.
-- ---------------------------------------------------------------------------

create table guest_change (
    id              bigint      generated by default as identity primary key,
    -- Its own aggregate root, so it carries wedding_id: change rows are never
    -- loaded with a guest (thousands of them) and are queried independently.
    wedding_id      bigint      not null references wedding (id),
    guest_id        bigint      not null references guest (id),
    -- One row per changed FIELD, not per save.
    field_name      varchar(50) not null,
    -- text rather than a sized varchar: these hold the rendered old and new
    -- value of whatever field changed, so the widest column in `guest` is a
    -- floor that would have to be chased every time one grows. Null means the
    -- field was empty on that side, which for a nullable column is a real
    -- change worth recording.
    old_value       text,
    new_value       text,
    -- MANUAL / VENDOR_EMAIL / IMPORT. varchar, not an enum.
    source          varchar(20) not null,
    changed_by      bigint      not null references app_user (id),
    changed_at      timestamptz not null,
    -- Exactly one of these is set when source names a channel, and neither
    -- when it is MANUAL. Not expressed as a CHECK constraint: #25 owns the
    -- write path and has not been built, and a hand-applied constraint that
    -- turns out slightly wrong is more expensive to undo than to add.
    email_ingest_id bigint references email_ingest (id),
    guest_import_id bigint references guest_import (id)
);

-- "This wedding's history", newest first.
create index ix_guest_change_wedding_changed_at
    on guest_change (wedding_id, changed_at desc);

-- "Who changed this number", for one guest.
create index ix_guest_change_guest_changed_at
    on guest_change (guest_id, changed_at desc);
